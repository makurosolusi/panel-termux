#!/bin/sh
# Packages the release assets (run by .github/workflows/release.yml, or locally).
# Usage: sh scripts/package-release.sh <binary> <outdir> <tag>
# Writes into <outdir> (PLAN/07 §8.2): panel (the raw android-arm64 binary), install.sh (install-release.sh with the
# tag baked in), panel-termux-android-arm64.tar.gz and SHA256SUMS covering all three.
# install.sh and the tarball stay through 0.6.x and go away in 0.7.0.
set -eu

die() { echo "package-release: $*" >&2; exit 1; }

[ $# -eq 3 ] || die "usage: sh scripts/package-release.sh <binary> <outdir> <tag>"
BIN=$1
OUT=$2
TAG=$3
case "$TAG" in
  *[!0-9A-Za-z.-]*) die "tag may only contain letters, digits, '.' and '-', got '$TAG'" ;;
  v[0-9]*) ;;
  *) die "tag must look like v1.2.3, got '$TAG'" ;;
esac
[ -f "$BIN" ] || die "binary $BIN not found"
ROOT=$(cd "$(dirname "$0")/.." && pwd)
TARBALL=panel-termux-android-arm64.tar.gz

STAGE=$(mktemp -d)
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/scripts" "$OUT"
cp "$BIN" "$OUT/panel"
chmod 755 "$OUT/panel"
cp "$BIN" "$STAGE/panel-android-arm64"
chmod 755 "$STAGE/panel-android-arm64"
# install.sh <= 0.5.0 runs `sh scripts/install-phone.sh ./panel-android-arm64` from the extracted tarball; this
# generated stand-in hands over to `panel init` with the D6 tty fix (PLAN/07 K15).
cat >"$STAGE/scripts/install-phone.sh" <<'EOF'
#!/bin/sh
# Generated by scripts/package-release.sh for install.sh <= 0.5.0: `panel init` does the install now.
set -eu
[ $# -ge 1 ] || { echo "usage: sh scripts/install-phone.sh <binary>" >&2; exit 1; }
BIN=$1
shift
if [ ! -t 0 ] && (: </dev/tty) 2>/dev/null; then exec "$BIN" init "$@" </dev/tty; else exec "$BIN" init "$@"; fi
EOF
echo "$TAG" >"$STAGE/VERSION"

# Fixed file order; COPYFILE_DISABLE keeps macOS tar from adding ._ metadata files.
COPYFILE_DISABLE=1 tar -czf "$OUT/$TARBALL" -C "$STAGE" panel-android-arm64 scripts/install-phone.sh VERSION

grep -q '^PANEL_VERSION_DEFAULT=""$' "$ROOT/scripts/install-release.sh" ||
  die "scripts/install-release.sh lost its PANEL_VERSION_DEFAULT=\"\" line"
sed "s/^PANEL_VERSION_DEFAULT=\"\"\$/PANEL_VERSION_DEFAULT=\"$TAG\"/" "$ROOT/scripts/install-release.sh" >"$OUT/install.sh"

(cd "$OUT" && sha256sum panel "$TARBALL" install.sh >SHA256SUMS)
echo "packaged $TAG into $OUT: panel $TARBALL install.sh SHA256SUMS"
